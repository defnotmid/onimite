-- Per-frame jitter in -30..29, the same for a given frame and seed.
local function noise(index, seed)
  local x = math.sin(index * 12.9898 + seed * 78.233) * 43758.5453
  return math.floor((x - math.floor(x)) * 60) - 30
end

